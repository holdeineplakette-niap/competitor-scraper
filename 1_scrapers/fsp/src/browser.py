"""FSP browser side: the console snippet that fetches fsp.de from a person's own browser, and the import of its download.

fsp.de answers requests from datacenter IP ranges (the GitHub runner) with HTTP 403; from an office or home connection
plain HTTP works. So the monthly FSP data comes from the same browser step as TÜV SÜD: the snippet runs on
www.fsp.de/standorte in the DevTools console and fetches exactly the pages `fsp.run` would fetch (robots.txt, the HU
list, the all-services list, the sitemap, the detail pages of sitemap-only sites), one at a time, 2-4 s apart. It stops
at the first block (HTTP 403/503, a Cloudflare page) and does not retry it. Nothing is faked: no headers, no cookies, no
proxy; the browser sends its own requests from the page.

The download (`fsp_YYYY-MM-DD_HHMM.jsonl`) is turned into a normal `output/<stamp>_full` run: the raw files are written
in the layout of a `fsp.run` full run and parsed offline by `fsp.run` itself, with all its checks. The 2.3 MB inline SVG
of every list page is cut in the browser (`<svg></svg>`), which keeps the file at ~15 MB instead of ~125 MB; the parse
does not read SVGs (proven on the 2026-11-02 run: identical CSV).

The HU filter (`d=hauptuntersuchung`) is disallowed by fsp.de's robots.txt; Nikos decided to disregard that (2026-10-06),
as for the PC runs.
"""

from __future__ import annotations

import gzip
import hashlib
import json
import re
import shutil
import tempfile
from dataclasses import dataclass
from datetime import datetime
from pathlib import Path

from core import paths

from fsp import run as fsp_run
from fsp.fetch import BASE, DELAY_RANGE, MAX_RETRIES, BACKOFF_SECONDS, TIMEOUT
from fsp.parse import RESULTS_HEADING
from fsp.recon import CENTER, MAX_PAGES, OfflineClient

SLUG = "fsp"
SNIPPET_VERSION = "1"
SNIPPET_NAME = "fsp_snippet.js"
HOSTNAME = "www.fsp.de"
PAGE_URL = f"{BASE}/standorte"
SUMMARY_FILE = "browser_summary.json"
UPLOAD_RE = re.compile(r"^fsp_\d{4}-\d{2}-\d{2}_\d{4}\.jsonl$")
MAX_UPLOAD_BYTES = 100 * 1024 * 1024
# the files a snippet may deliver, in the layout of a fsp.run full run (OfflineClient reads both .html and .html.gz)
FILE_RE = re.compile(r"^raw/(robots\.txt|pages/(hu|all)_page_\d{2}\.html|sitemap/sitemap\.xml|detail/(?!\.)[\w.%-]+\.html)$")
REQUIRED = ("raw/robots.txt", "raw/pages/hu_page_01.html", "raw/pages/all_page_01.html", "raw/sitemap/sitemap.xml")


class ImportProblem(ValueError):
    """A downloaded file that cannot be used; nothing was written to output/."""


class Blocked(ImportProblem):
    """The snippet stopped because fsp.de refused the browser's requests too."""


# --------------------------------------------------------------------------
# The snippet
# --------------------------------------------------------------------------

_TEMPLATE = r"""// FSP locator - monthly run of the Pruefstellen sourcing (snippet version __VERSION__).
// Generated by fsp/browser.py. Do not edit.
//
// How to run (about 3 minutes):
//   1. Open __PAGE__ in your normal browser (accept or close the cookie banner).
//   2. Open DevTools > Console, paste this whole file, press Enter (the first time Chrome asks you to type: allow pasting).
//   3. Wait. Progress is printed per page. The file fsp_*.jsonl downloads at the end (also after a stop).
//   Stop early: type  window.fspStop = true  (the current request finishes first, the download still happens).
// The script fetches the locator's own pages from this page, one at a time, 2-4 s apart: robots.txt, the HU list, the
// all-services list, the sitemap and the detail pages of sites only the sitemap lists (about 50 requests). A refusal
// (HTTP 403/503, a Cloudflare page) stops it at once; HTTP 429/5xx gets at most __RETRIES__ retries. Nothing else is sent.
(async () => {
  "use strict";
  const VERSION = "__VERSION__";
  const HOSTNAME = "__HOSTNAME__";
  const CENTER = __CENTER__;
  const MAX_PAGES = __MAX_PAGES__, MAX_DETAIL = __MAX_DETAIL__;
  const DELAY_MS = __DELAY__, BACKOFF_MS = __BACKOFF__, TIMEOUT_MS = __TIMEOUT__;
  const HEADING = __HEADING__;

  if (location.hostname !== HOSTNAME) {
    console.error("Wrong page: open https://" + HOSTNAME + "/standorte first (this page is " + location.hostname + "). Nothing was sent.");
    return;
  }
  if (window.fspRunning) {
    console.error("The FSP snippet is already running in this tab. Type window.fspStop = true to stop it.");
    return;
  }
  window.fspRunning = true;
  window.fspStop = false;
  window.fspDone = false;

  const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));
  const pad = (n) => String(n).padStart(2, "0");
  const local = (d) => d.getFullYear() + "-" + pad(d.getMonth() + 1) + "-" + pad(d.getDate()) + "T" + pad(d.getHours()) + ":" + pad(d.getMinutes()) + ":" + pad(d.getSeconds());
  const clean = (s) => (s || "").replace(/\s+/g, " ").trim();
  const stripSvg = (t) => t.replace(/<svg\b[\s\S]*?<\/svg>/gi, "<svg></svg>");
  const lines = [];
  const started = new Date();
  let requests = 0, last = 0, stopped = null;

  class Stop extends Error {}

  // one GET, paced; a refusal stops for good, 429/5xx/network errors get a few retries
  async function get(url, label) {
    for (let attempt = 0; ; attempt++) {
      if (window.fspStop) throw new Stop("user_stop");
      const wait = last ? DELAY_MS[0] + Math.random() * (DELAY_MS[1] - DELAY_MS[0]) - (Date.now() - last) : 0;
      if (wait > 0) await sleep(wait);
      const controller = new AbortController();
      const timer = setTimeout(() => controller.abort(), TIMEOUT_MS);
      let status = 0, text = "", error = "";
      try {
        const resp = await fetch(url, { credentials: "same-origin", signal: controller.signal });
        status = resp.status;
        text = await resp.text();
      } catch (e) {
        error = String(e);
      } finally {
        clearTimeout(timer);
        last = Date.now();
        requests++;
      }
      const head = text.slice(0, 200000);
      if (status === 403 || status === 503 || head.includes("Just a moment") || head.includes("cf-chl")) {
        stopped = { reason: "blocked", label: label, url: url, status: status, first_200_chars: text.slice(0, 200) };
        throw new Stop("blocked");
      }
      if (status === 200) return text;
      if ((status === 429 || status >= 500 || status === 0) && attempt < BACKOFF_MS.length) {
        console.warn(label + ": " + (error || "HTTP " + status) + ", retry in " + BACKOFF_MS[attempt] / 1000 + " s");
        await sleep(BACKOFF_MS[attempt]);
        continue;
      }
      stopped = { reason: "http_error", label: label, url: url, status: status, error: error };
      throw new Stop("http_error");
    }
  }

  function keep(path, url, text) {
    lines.push(JSON.stringify({ file: path, url: url, text: text }));
  }

  // the cards of one list page: [slug or ""], and whether it is a real result page (heading present)
  function listPage(text) {
    const doc = new DOMParser().parseFromString(text, "text/html");
    const h1 = doc.querySelector("h1");
    const heading = !!h1 && clean(h1.textContent).includes(HEADING);
    const slugs = [];
    for (const card of doc.querySelectorAll("div.location.card")) {
      let slug = "";
      for (const a of card.querySelectorAll("a[href]")) {
        if (a.closest("span.icon-label") || !clean(a.textContent).includes("Mehr erfahren")) continue;
        const path = a.getAttribute("href").replace(/^[a-z]+:\/\/[^/]+/i, "").split(/[?#]/)[0];
        const m = path.match(/^\/standorte\/([^/?#]+)\/?$/);
        if (m) slug = m[1];
      }
      slugs.push(slug);
    }
    return { heading: heading, slugs: slugs };
  }

  async function crawl(label, params, all) {
    const seen = new Set();
    for (let n = 1; n <= MAX_PAGES; n++) {
      const q = new URLSearchParams({ ...params, page: String(n) });
      const url = location.origin + "/standorte?" + q.toString();
      const text = await get(url, label + " page " + n);
      keep("raw/pages/" + label + "_page_" + pad(n) + ".html", url, stripSvg(text));
      const page = listPage(text);
      if (!page.slugs.length && !page.heading) {
        stopped = { reason: "not_a_result_page", label: label, page: n, first_200_chars: text.slice(0, 200) };
        throw new Stop("not_a_result_page");
      }
      const found = page.slugs.filter((s) => s && !seen.has(s));
      console.log("[" + label + "] page " + n + ": " + page.slugs.length + " cards, " + found.length + " new");
      if (!page.slugs.length || !found.length) return;
      found.forEach((s) => { seen.add(s); all && all.add(s); });
    }
  }

  try {
    let url = location.origin + "/robots.txt";
    keep("raw/robots.txt", url, await get(url, "robots.txt"));
    const base = { lat: String(CENTER.lat), lng: String(CENTER.lng), r: "1000" };
    await crawl("hu", { ...base, d: "hauptuntersuchung" }, null);
    const listed = new Set();
    await crawl("all", base, listed);
    url = location.origin + "/sitemap.xml";
    const xml = await get(url, "sitemap");
    keep("raw/sitemap/sitemap.xml", url, xml);
    const sm = new DOMParser().parseFromString(xml, "application/xml");
    if (sm.documentElement.localName === "sitemapindex") {
      stopped = { reason: "sitemap_index", message: "the sitemap became an index: not handled, tell the project owner" };
      throw new Stop("sitemap_index");
    }
    const inSitemap = new Set();
    for (const loc of sm.getElementsByTagName("loc")) {
      let path = "";
      try { path = decodeURIComponent(new URL(loc.textContent.trim()).pathname); } catch (e) { continue; }
      const m = path.match(/^\/standorte\/([^/?#]+)\/?$/);
      if (m) inSitemap.add(m[1]);
    }
    const only = [...inSitemap].filter((s) => !listed.has(s)).sort().slice(0, MAX_DETAIL);
    console.log("sitemap: " + inSitemap.size + " sites, " + only.length + " only in the sitemap");
    for (const slug of only) {
      url = location.origin + "/standorte/" + slug;
      keep("raw/detail/" + slug + ".html", url, stripSvg(await get(url, "detail " + slug)));
    }
  } catch (e) {
    if (!(e instanceof Stop)) stopped = { reason: "exception", message: String(e) };
    else if (!stopped) stopped = { reason: e.message };
  }

  const finished = new Date();
  lines.push(JSON.stringify({ file: "browser_summary.json", response: {
    snippet_version: VERSION, started: local(started), finished: local(finished), requests: requests,
    files: lines.length, complete: !stopped, stopped_reason: stopped, user_agent: navigator.userAgent,
  } }));
  const fileName = "fsp_" + local(finished).slice(0, 10) + "_" + pad(finished.getHours()) + pad(finished.getMinutes()) + ".jsonl";
  const text = lines.join("\n") + "\n";
  window.fspResult = text;  // in memory only: if the download is blocked, copy(window.fspResult) puts it on the clipboard
  window.fspFileName = fileName;
  const blob = new Blob([text], { type: "application/x-ndjson" });
  const href = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.href = href;
  link.download = fileName;
  document.body.appendChild(link);
  link.click();
  link.remove();
  setTimeout(() => URL.revokeObjectURL(href), 10000);
  window.fspRunning = false;
  window.fspDone = true;
  if (stopped) console.warn("FSP STOPPED after " + requests + " requests: " + JSON.stringify(stopped));
  else console.log("FSP finished: " + requests + " requests.");
  console.log("Downloaded " + fileName + " (" + (text.length / 1e6).toFixed(1) + " MB). Post it in the same Slack thread as TÜV SÜD." +
    " (No file? Type copy(window.fspResult) and paste the clipboard into a new file " + fileName + ".)");
})();
"""


def render_snippet(delay_range: tuple[float, float] = DELAY_RANGE, backoff_s: tuple[float, ...] = BACKOFF_SECONDS[:MAX_RETRIES]) -> str:
    """The console snippet. Every crawl constant comes from the Python side, so the browser fetches what fsp.run reads.
    delay_range / backoff_s: only tests change them (the offline browser test runs without pauses)."""
    values = {
        "__VERSION__": SNIPPET_VERSION,
        "__PAGE__": PAGE_URL,
        "__HOSTNAME__": HOSTNAME,
        "__CENTER__": json.dumps(CENTER),
        "__MAX_PAGES__": str(MAX_PAGES),
        "__MAX_DETAIL__": str(fsp_run.MAX_SITEMAP_ONLY),
        "__DELAY__": json.dumps([int(delay_range[0] * 1000), int(delay_range[1] * 1000)]),
        "__BACKOFF__": json.dumps([int(s * 1000) for s in backoff_s]),
        "__RETRIES__": str(len(backoff_s)),
        "__TIMEOUT__": str(TIMEOUT * 1000),
        "__HEADING__": json.dumps(RESULTS_HEADING),
    }
    text = _TEMPLATE
    for token, value in values.items():
        text = text.replace(token, value)
    return text


def write_snippet(path: Path) -> Path:
    """Write the snippet (overwrites: it is the same text for every month of one snippet version)."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_snippet(), encoding="utf-8", newline="\n")
    return path


# --------------------------------------------------------------------------
# The downloaded file
# --------------------------------------------------------------------------

@dataclass
class Download:
    files: dict[str, str]  # raw path -> text
    summary: dict
    started: datetime
    sha256: str
    name: str


def file_sha256(path: Path) -> str:
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def read_download(path: Path) -> Download:
    """Parse and validate a downloaded file. Raises ImportProblem (Blocked for a refusal) and changes nothing.

    Checks: every line is {file, url, text} or the closing browser_summary.json; the file names are the raw layout of a
    fsp.run run (no other path can be written); no file twice; the summary is for this snippet version and says the run is
    complete; the required files are there. Completeness of the lists and the sitemap is fsp.run's own job (its checks).
    """
    path = Path(path)
    if not path.is_file():
        raise ImportProblem(f"file not found: {path}")
    if path.stat().st_size > MAX_UPLOAD_BYTES:
        raise ImportProblem(f"{path.name} is larger than {MAX_UPLOAD_BYTES // 2**20} MB")
    parsed = []
    with open(path, encoding="utf-8-sig") as fh:  # iterate: str.splitlines() would also split at U+2028 inside strings
        for number, line in enumerate(fh, 1):
            if not line.strip():
                continue
            try:
                obj = json.loads(line)
            except ValueError as exc:
                raise ImportProblem(f"{path.name} line {number} is not JSON ({exc})") from exc
            if not isinstance(obj, dict) or not isinstance(obj.get("file"), str):
                raise ImportProblem(f"{path.name} line {number} has no file name")
            parsed.append((number, obj))
    if not parsed:
        raise ImportProblem(f"{path.name} is empty")
    number, last = parsed[-1]
    if last["file"] != SUMMARY_FILE or not isinstance(last.get("response"), dict):
        raise ImportProblem(f"{path.name} has no {SUMMARY_FILE} line at the end: the download is incomplete")
    summary = last["response"]
    for key in ("snippet_version", "started", "finished", "requests", "complete", "stopped_reason"):
        if key not in summary:
            raise ImportProblem(f"the browser summary lacks {key!r}")
    if str(summary["snippet_version"]) != SNIPPET_VERSION:
        raise ImportProblem(f"{path.name} comes from snippet version {summary['snippet_version']}, this code reads {SNIPPET_VERSION}")
    stop = summary["stopped_reason"]
    if isinstance(stop, dict) and stop.get("reason") == "blocked":
        raise Blocked(f"fsp.de refused the browser's request ({stop.get('label')}: HTTP {stop.get('status')}); nothing is retried")
    if not summary["complete"] or stop:
        raise ImportProblem(f"the snippet stopped before the end ({json.dumps(stop, ensure_ascii=False)[:300]}): run it again")
    try:
        started = datetime.fromisoformat(summary["started"]).replace(tzinfo=None, second=0, microsecond=0)
    except (TypeError, ValueError) as exc:
        raise ImportProblem(f"the browser summary has no valid start time ({summary['started']!r})") from exc
    files: dict[str, str] = {}
    for number, obj in parsed[:-1]:
        name = obj["file"]
        if name == SUMMARY_FILE:
            raise ImportProblem(f"{path.name} line {number}: a second summary line")
        if not FILE_RE.match(name):
            raise ImportProblem(f"{path.name} line {number}: unexpected file name {name!r}")
        if name in files:
            raise ImportProblem(f"{path.name} holds {name} twice")
        if not isinstance(obj.get("text"), str):
            raise ImportProblem(f"{path.name} line {number} ({name}) has no text")
        files[name] = obj["text"]
    missing = [r for r in REQUIRED if r not in files]
    if missing:
        raise ImportProblem(f"{path.name} lacks {', '.join(missing)}")
    return Download(files=files, summary=summary, started=started, sha256=file_sha256(path), name=path.name)


class BrowserClient(OfflineClient):
    """Serves the browser's files; requests_made is what the browser sent (shown in the run summary)."""

    def __init__(self, folder: Path, requests_made: int):
        super().__init__([folder])
        self.requests_made = requests_made


def _write_raw(folder: Path, files: dict[str, str]) -> None:
    for rel, text in files.items():
        target = folder / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        if rel.startswith("raw/pages/"):  # stored gzipped like the list pages of a fsp.run full run
            with gzip.open(target.with_name(target.name + ".gz"), "wt", encoding="utf-8") as fh:
                fh.write(text)
        else:
            target.write_text(text, encoding="utf-8")


def import_download(path: Path, root=None, say=print) -> fsp_run.RunResult:
    """Validate the download and turn it into output/<browser start>_full: raw files + fsp.run's offline parse and checks.

    The run counts like a PC full run (its data started when the browser started). A failed parse leaves a FAIL run
    folder, as a failed live run would; the master then keeps the last passing run."""
    d = read_download(path)
    out = paths.output_dir(SLUG, "full", root)
    before = {p.name for p in out.iterdir()} if out.is_dir() else set()
    origin = {"fetched_by": "browser snippet", "upload_file": d.name, "upload_sha256": d.sha256,
              "snippet_version": d.summary["snippet_version"], "browser_started": d.summary["started"],
              "browser_finished": d.summary["finished"], "browser_requests": d.summary["requests"]}
    with tempfile.TemporaryDirectory(prefix="fsp_upload_") as tmp:
        stage = Path(tmp)
        _write_raw(stage, d.files)
        try:
            result = fsp_run.run("full", confirm_full_run=True, root=root, now=d.started, allow_robots_disallowed=True,
                                 client=BrowserClient(stage, int(d.summary["requests"] or 0)), save_raw=False, origin=origin)
        finally:  # the run folder keeps the raw files, as a live run's folder does (also when the parse failed)
            new = sorted({p.name for p in out.iterdir()} - before) if out.is_dir() else []
            if new:
                shutil.copytree(stage / "raw", out / new[-1] / "raw")
        say(f"FSP upload {d.name}: {result.outcome}, {len(result.frame)} in scope -> {result.run_dir.name}")
        return result


def imported_before(sha256: str, root=None) -> Path | None:
    """The run folder that already holds this exact upload (n8n may deliver a file twice), or None."""
    out = paths.output_dir(SLUG, "full", root)
    for f in sorted(out.glob(f"*/{paths.RUN_SUMMARY_JSON}"), reverse=True) if out.is_dir() else []:
        try:
            s = json.loads(f.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            continue
        if (s.get("origin") or {}).get("upload_sha256") == sha256:
            return f.parent
    return None
