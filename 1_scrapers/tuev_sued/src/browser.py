"""TÜV SÜD browser side: render the console snippet of a pass and import the file it downloads.

tuvsud.com answers scripted requests with a Cloudflare challenge. Management approved (2026-10-05) running the queries
in Nikos's own, normal browser session from the DevTools console (0_instructions/sources/tuev_sued.md §2). Python
therefore makes NO request to TÜV SÜD; it only writes the snippet (`tuev_sued_passNN.js`) and reads the file the snippet
downloads (`raw_passNN.jsonl`). Boundaries that stay in this code: no headless browser or automation, no faked headers
or fingerprints, no challenge solver, no cookies copied into Python; the snippet sends the page's own request from the
page, one at a time, 5 s + 0-2 s apart, at most one request per planned PLZ (max 200; a retry counts as one), and stops
for good at the first answer that is not the expected JSON: at once if it looks like a challenge or refusal, after one
retry (30 s later) otherwise. If the in-browser requests get challenged too, the pass is a "block": the run stops.
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass, field
from pathlib import Path

from tuev_sued import parse

SNIPPET_VERSION = "1"
ENDPOINT = "https://www.tuvsud.com/astscsearch/api/tscsearch/searchTSCLocation"
HOSTNAME = "www.tuvsud.com"
PAGE_URL = "https://www.tuvsud.com/de-de/branchen/mobilitaet-und-automotive/hauptuntersuchung/service-center-und-termin"
MAX_PLZ = 200  # hard ceiling of requests per pass
PACE_S, JITTER_S, TIMEOUT_S, RETRY_WAIT_S = 5, 2, 60, 30
# Content headers of the request. The page sets Accept, Origin and Referer itself; only the body type is ours.
# To check against the request captured in DevTools (Network tab) before the first live pass.
HEADERS = {"Content-Type": "application/json"}
SUMMARY_FILE = "browser_summary.json"
BLOCK_STATUSES = (403, 429, 503)


class ImportProblem(ValueError):
    """A downloaded pass file that cannot be used; nothing was copied into the run folder."""


@dataclass
class PassPlan:
    """The queries of one pass: (PLZ, reason) in the order the snippet asks them."""

    pass_no: int
    queries: list[tuple[str, str]]
    mode: str = "full"
    snippet_version: str = SNIPPET_VERSION
    run_folder: Path | None = None
    js_path: Path | None = None

    @property
    def zips(self) -> list[str]:
        return [z for z, _ in self.queries]

    def as_dict(self) -> dict:
        return {
            "pass": self.pass_no, "mode": self.mode, "snippet_version": self.snippet_version,
            "plz": self.zips, "reasons": [r for _, r in self.queries],
        }


def pass_js_name(pass_no: int) -> str:
    return f"tuev_sued_pass{pass_no:02d}.js"


def raw_pass_name(pass_no: int) -> str:
    return f"raw_pass{pass_no:02d}.jsonl"


def passes_planned(folder: Path) -> list[int]:
    return sorted(int(m.group(1)) for p in Path(folder).glob("tuev_sued_pass*.js") if (m := re.fullmatch(r"tuev_sued_pass(\d+)\.js", p.name)))


def passes_imported(folder: Path) -> list[int]:
    return sorted(int(m.group(1)) for p in Path(folder).glob("raw_pass*.jsonl") if (m := re.fullmatch(r"raw_pass(\d+)\.jsonl", p.name)))


# --------------------------------------------------------------------------
# The snippet
# --------------------------------------------------------------------------

_TEMPLATE = r"""// TUEV SUED HU finder - pass __PASS__ of the Pruefstellen sourcing (snippet version __VERSION__, __N__ PLZ).
// Generated by tuev_sued/browser.py. Do not edit: plan a new pass instead.
//
// How to run (about __MINUTES__ minutes):
//   1. Open __PAGE__ in your normal browser,
//      accept the cookies and search one PLZ by hand, so that the page is fully loaded.
//   2. Open DevTools > Console, paste this whole file, press Enter.
//   3. Wait. Progress is printed per PLZ. The file tuev_sued_pass__PASS__*.jsonl downloads at the end (also after a stop).
//   Stop early: type  window.tuevSuedStop = true  (the current request finishes first, the download still happens).
// The script only calls the finder from this page, one request at a time. A challenge or refusal (HTTP 403/429/503, an HTML
// page) stops it at once; any other answer that is not the expected JSON gets one retry after 30 s, then it stops too.
// Nothing else is sent, stored or loaded.
(async () => {
  "use strict";
  const PLAN = __PLAN__;
  const ENDPOINT = "__ENDPOINT__";
  const HOSTNAME = "__HOSTNAME__";
  const HEADERS = __HEADERS__;
  const PACE_MS = __PACE__, JITTER_MS = __JITTER__, TIMEOUT_MS = __TIMEOUT__, RETRY_WAIT_MS = __RETRY_WAIT__;
  const MAX_PLZ = __MAX_PLZ__;

  if (location.hostname !== HOSTNAME) {
    console.error("Wrong page: open the TUEV SUED HU finder on " + HOSTNAME + " first (this page is " + location.hostname + "). Nothing was sent.");
    return;
  }
  if (window.tuevSuedRunning) {
    console.error("A pass is already running in this tab. Type window.tuevSuedStop = true to stop it.");
    return;
  }
  window.tuevSuedRunning = true;
  window.tuevSuedStop = false;

  const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));
  const pad = (n) => String(n).padStart(2, "0");
  const isNum = (v) => v !== null && v !== undefined && v !== "" && Number.isFinite(Number(v));
  const valid = (d) => d !== null && typeof d === "object" && Array.isArray(d.finaltsc) && isNum(d.lat) && isNum(d.lon);
  const list = PLAN.plz.slice(0, MAX_PLZ);
  const ceiling = list.length;  // never more requests than PLZ in the list; a retry counts as a request
  const lines = [];
  const started = new Date();
  let sent = 0, done = 0, stopped = null;

  async function ask(plz) {
    const controller = new AbortController();
    const timer = setTimeout(() => controller.abort(), TIMEOUT_MS);
    try {
      const resp = await fetch(ENDPOINT, {
        method: "POST", credentials: "same-origin", headers: HEADERS,
        body: JSON.stringify({ searchTerm: plz, hu: 1 }), signal: controller.signal,
      });
      const text = await resp.text();
      let ok = false;
      if (resp.status === 200) {
        try { ok = valid(JSON.parse(text)); } catch (e) { ok = false; }
      }
      return { ok: ok, status: resp.status, type: resp.headers.get("content-type") || "", text: text };
    } catch (e) {
      return { ok: false, status: 0, type: "", text: String(e) };
    } finally {
      clearTimeout(timer);
    }
  }

  const failure = (r, plz) => ({
    reason: "invalid_answer", plz: plz, status: r.status, content_type: r.type, first_200_chars: r.text.slice(0, 200),
  });
  // HTTP 403 / 429 / 503, an HTML page instead of JSON, or challenge wording: the site does not want this traffic
  const looksBlocked = (r) => [403, 429, 503].includes(r.status) || /html/i.test(r.type) || /just a moment|challenge/i.test(r.text.slice(0, 200));

  try {
    for (let i = 0; i < list.length; i++) {
      const plz = list[i];
      if (window.tuevSuedStop) { stopped = { reason: "user_stop", next_plz: plz }; break; }
      if (i > 0) {
        await sleep(PACE_MS + Math.random() * JITTER_MS);
        if (window.tuevSuedStop) { stopped = { reason: "user_stop", next_plz: plz }; break; }
      }
      if (sent >= ceiling) { stopped = { reason: "request_ceiling", next_plz: plz }; break; }
      let r = await ask(plz);
      sent++;
      if (!r.ok && looksBlocked(r)) { stopped = failure(r, plz); break; }  // a challenge or refusal: stop at once, no retry
      if (!r.ok) {
        console.warn("No valid answer for " + plz + " (HTTP " + r.status + "). Waiting " + RETRY_WAIT_MS / 1000 + " s, then one retry.");
        await sleep(RETRY_WAIT_MS);
        if (sent >= ceiling) { stopped = failure(r, plz); break; }
        r = await ask(plz);
        sent++;
        if (!r.ok) { stopped = failure(r, plz); break; }
      }
      const data = JSON.parse(r.text);
      const name = "pass" + pad(PLAN.pass) + "_q" + String(i + 1).padStart(3, "0") + "_" + plz + ".json";
      // the answer exactly as received (one line; newlines outside strings are only whitespace)
      lines.push('{"file":' + JSON.stringify(name) + ',"response":' + r.text.replace(/[\r\n]+/g, " ").trim() + "}");
      done++;
      const last = data.finaltsc.length ? data.finaltsc[data.finaltsc.length - 1] : null;
      const lastKm = last ? (isNum(last.sortdistance) ? Number(last.sortdistance) : Number(last.distance)) : NaN;
      console.log((i + 1) + "/" + list.length + " " + plz + " → " + data.finaltsc.length + " sites, last " + (Number.isFinite(lastKm) ? lastKm.toFixed(1) + " km" : "n/a"));
    }
  } catch (e) {
    stopped = { reason: "exception", message: String(e) };
  }

  const finished = new Date();
  const summary = {
    pass: PLAN.pass, planned: list.length, done: done, started: started.toISOString(), finished: finished.toISOString(),
    stopped_reason: stopped, snippet_version: PLAN.snippet_version,
  };
  lines.push(JSON.stringify({ file: "browser_summary.json", response: summary }));
  window.tuevSuedRunning = false;
  const fileName = "tuev_sued_pass" + pad(PLAN.pass) + "_" + finished.getFullYear() + "-" + pad(finished.getMonth() + 1) + "-" + pad(finished.getDate()) +
    "_" + pad(finished.getHours()) + pad(finished.getMinutes()) + ".jsonl";
  const text = lines.join("\n") + "\n";
  window.tuevSuedResult = text;  // in memory only: if the download is blocked, copy(window.tuevSuedResult) puts it on the clipboard
  const blob = new Blob([text], { type: "application/x-ndjson" });
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.href = url;
  link.download = fileName;
  document.body.appendChild(link);
  link.click();
  link.remove();
  setTimeout(() => URL.revokeObjectURL(url), 10000);
  if (stopped) {
    console.warn("Pass " + PLAN.pass + " STOPPED after " + done + "/" + list.length + ": " + JSON.stringify(stopped));
  } else {
    console.log("Pass " + PLAN.pass + " finished: " + done + "/" + list.length + ".");
  }
  console.log("Downloaded " + fileName + ". Next: run `check` in the notebook with this file. (No file? Type copy(window.tuevSuedResult) and paste the clipboard into a new .jsonl file.)");
})();
"""


def render_snippet(plan: PassPlan) -> str:
    """The console snippet of a pass: the PLZ list and the pass number are embedded."""
    if not plan.queries:
        raise ValueError("a pass needs at least one PLZ")
    if len(plan.queries) > MAX_PLZ:
        raise ValueError(f"a pass holds at most {MAX_PLZ} PLZ, got {len(plan.queries)}")
    if any(not re.fullmatch(r"\d{5}", z) for z in plan.zips):
        raise ValueError("PLZ must be 5-digit text")
    minutes = round(len(plan.queries) * (PACE_S + JITTER_S / 2 + 1.0) / 60)
    values = {
        "__PASS__": f"{plan.pass_no:02d}",
        "__VERSION__": plan.snippet_version,
        "__N__": str(len(plan.queries)),
        "__MINUTES__": str(max(1, minutes)),
        "__PAGE__": PAGE_URL,
        "__PLAN__": json.dumps(plan.as_dict(), ensure_ascii=True),
        "__ENDPOINT__": ENDPOINT,
        "__HOSTNAME__": HOSTNAME,
        "__HEADERS__": json.dumps(HEADERS),
        "__PACE__": str(PACE_S * 1000),
        "__JITTER__": str(JITTER_S * 1000),
        "__TIMEOUT__": str(TIMEOUT_S * 1000),
        "__RETRY_WAIT__": str(RETRY_WAIT_S * 1000),
        "__MAX_PLZ__": str(MAX_PLZ),
    }
    text = _TEMPLATE
    for token, value in values.items():
        text = text.replace(token, value)
    return text


def write_snippet(folder: Path, plan: PassPlan) -> Path:
    """Write tuev_sued_passNN.js into the run folder (never over an existing file)."""
    path = Path(folder) / pass_js_name(plan.pass_no)
    with open(path, "x", encoding="utf-8", newline="\n") as fh:
        fh.write(render_snippet(plan))
    plan.js_path, plan.run_folder = path, Path(folder)
    return path


def read_plan(js_path: Path) -> PassPlan:
    """The plan embedded in a snippet file (the `const PLAN = {...};` line)."""
    text = Path(js_path).read_text(encoding="utf-8")
    m = re.search(r"^\s*const PLAN = (\{.*\});\s*$", text, re.MULTILINE)
    if not m:
        raise ImportProblem(f"{Path(js_path).name} holds no PLAN line")
    data = json.loads(m.group(1))
    return PassPlan(
        pass_no=int(data["pass"]), queries=list(zip(data["plz"], data["reasons"])), mode=data.get("mode", "full"),
        snippet_version=data.get("snippet_version", SNIPPET_VERSION), run_folder=Path(js_path).parent, js_path=Path(js_path),
    )


