@dataclass
class PassImport:
    """A validated pass file: its answers (name, response) in file order and the browser's own summary."""

    pass_no: int
    answers: list[tuple[str, dict]]
    summary: dict
    raw_path: Path | None = None
    problems: list[str] = field(default_factory=list)

    @property
    def stopped_reason(self) -> dict | None:
        return self.summary.get("stopped_reason")

    @property
    def blocked(self) -> bool:
        return is_block(self.stopped_reason)


def is_block(stopped_reason) -> bool:
    """True when the pass stopped because the site challenged or refused the request (HTTP 403/429/503, an HTML page
    instead of JSON, a Cloudflare challenge text). The run then stops; there is no workaround."""
    if not isinstance(stopped_reason, dict) or stopped_reason.get("reason") != "invalid_answer":
        return False
    status = stopped_reason.get("status")
    kind = str(stopped_reason.get("content_type") or "").lower()
    text = str(stopped_reason.get("first_200_chars") or "").lower()
    return status in BLOCK_STATUSES or "html" in kind or "just a moment" in text or "challenge" in text


def read_download(path: Path, plan: PassPlan) -> PassImport:
    """Parse and validate a downloaded pass file against its plan. Raises ImportProblem and changes nothing on a bad file.

    Checks: every line is {"file", "response"}; the last line is browser_summary.json; the summary is for this pass and
    this plan (planned, done); every answer is named passNN_qKKK_PLZ.json with PLZ = the plan's PLZ at position KKK, and
    has the finder's shape. A pass that stopped early is valid: it keeps what was collected.
    """
    path = Path(path)
    if not path.is_file():
        raise ImportProblem(f"file not found: {path}")
    lines = []
    with open(path, encoding="utf-8-sig") as fh:  # iterate: str.splitlines() would also split at U+2028 inside strings
        for number, line in enumerate(fh, 1):
            if line.strip():
                lines.append((number, line))
    if not lines:
        raise ImportProblem(f"{path.name} is empty")
    parsed = []
    for number, line in lines:
        try:
            obj = json.loads(line)
        except ValueError as exc:
            raise ImportProblem(f"{path.name} line {number} is not JSON ({exc})") from exc
        if not isinstance(obj, dict) or set(obj) != {"file", "response"} or not isinstance(obj["file"], str):
            raise ImportProblem(f"{path.name} line {number} is not a {{file, response}} object")
        parsed.append((number, obj["file"], obj["response"]))
    number, name, summary = parsed[-1]
    if name != SUMMARY_FILE:
        raise ImportProblem(f"{path.name} has no {SUMMARY_FILE} line at the end: the download is incomplete")
    for key in ("pass", "planned", "done", "started", "finished", "stopped_reason", "snippet_version"):
        if not isinstance(summary, dict) or key not in summary:
            raise ImportProblem(f"the browser summary lacks {key!r}")
    if summary["pass"] != plan.pass_no:
        raise ImportProblem(f"{path.name} is pass {summary['pass']}, but pass {plan.pass_no} is the one waiting")
    if summary["planned"] != len(plan.queries):
        raise ImportProblem(f"the file planned {summary['planned']} PLZ, the plan has {len(plan.queries)}: wrong snippet?")
    answers = []
    for number, name, response in parsed[:-1]:
        if name == SUMMARY_FILE:
            raise ImportProblem(f"{path.name} line {number}: a second summary line")
        fields = parse.parse_answer_name(name)
        if fields is None or fields[0] != plan.pass_no:
            raise ImportProblem(f"{path.name} line {number}: unexpected answer name {name!r}")
        _, seq, plz = fields
        if not 1 <= seq <= len(plan.queries) or plan.queries[seq - 1][0] != plz:
            raise ImportProblem(f"{path.name} line {number}: {name} does not match the plan (position {seq} is {plan.queries[seq - 1][0] if 1 <= seq <= len(plan.queries) else '-'})")
        try:
            parse.check_shape(response)
        except parse.ShapeError as exc:
            raise ImportProblem(f"{path.name} line {number} ({name}): {exc}") from exc
        answers.append((name, response))
    if len({n for n, _ in answers}) != len(answers):
        raise ImportProblem(f"{path.name} holds the same answer twice")
    if summary["done"] != len(answers):
        raise ImportProblem(f"the summary says {summary['done']} answers done, the file holds {len(answers)}")
    return PassImport(pass_no=plan.pass_no, answers=answers, summary=summary)


def import_pass(path: Path, folder: Path, plan: PassPlan) -> PassImport:
    """Validate the downloaded file and copy it into the run folder as raw_passNN.jsonl (never over an existing one)."""
    result = read_download(path, plan)
    target = Path(folder) / raw_pass_name(plan.pass_no)
    if target.exists():
        raise ImportProblem(f"{target.name} exists already: pass {plan.pass_no} was imported before")
    with open(target, "xb") as out:
        out.write(Path(path).read_bytes())
    result.raw_path = target
    return result
